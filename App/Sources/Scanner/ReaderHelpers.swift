import Foundation

// Helpers shared by the iOS and Mac readers.

enum Sysctl {
    static func string(_ name: String) -> String? {
        var size = 0
        guard sysctlbyname(name, nil, &size, nil, 0) == 0, size > 0 else { return nil }
        var buffer = [CChar](repeating: 0, count: size)
        guard sysctlbyname(name, &buffer, &size, nil, 0) == 0 else { return nil }
        return String(cString: buffer)
    }

    static func bootTime() -> Date? {
        var tv = timeval()
        var size = MemoryLayout<timeval>.size
        guard sysctlbyname("kern.boottime", &tv, &size, nil, 0) == 0 else { return nil }
        return Date(timeIntervalSince1970: TimeInterval(tv.tv_sec) + TimeInterval(tv.tv_usec) / 1_000_000)
    }
}

/// Finds a first name in a device name such as "Sam's AirPods".
enum OwnerName {
    static func find(in name: String) -> String? {
        let pattern = #/^([\p{L}][\p{L}\-]{1,20})['’]s\s/#
        guard let match = name.firstMatch(of: pattern) else { return nil }
        return String(match.1)
    }
}
